-- Like ordinary puzzle claims, these are bounded client assertions. The server
-- chooses the scope, first/replay amounts and daily cap, never a client amount.
create function public.claim_timed_challenge_coins(p_environment text,p_level_id text,p_attempt_id text)
returns public.coin_wallets language plpgsql security definer set search_path = '' as $$
declare v_key text; v_payload jsonb; v_entry public.coin_wallet_entries; v_ids text[];
 v_amount integer; v_count integer; v_total bigint; v_wallet public.coin_wallets;
begin
 if auth.uid() is null then raise exception 'Authentication required' using errcode='42501'; end if;
 if p_attempt_id is null or length(p_attempt_id) not between 1 and 200 then raise exception 'Invalid attempt'; end if;
 v_key:='reward:'||auth.uid()||':'||p_environment||':'||p_attempt_id;
 v_payload:=jsonb_build_object('timed_level_id',p_level_id);
 perform pg_advisory_xact_lock(hashtextextended(v_key,0));
 perform wallet_private.ensure_wallet(auth.uid(),p_environment);
 select * into v_entry from public.coin_wallet_entries where request_key=v_key;
 if found then
  if v_entry.request_payload<>v_payload then raise exception 'Attempt already used'; end if;
 else
  select puzzle_ids into v_ids from wallet_private.timed_challenge_catalog where level_id=p_level_id;
  if not found then raise exception 'Unknown timed level'; end if;
  select count(*),sum(2 * case when exists(select 1 from wallet_private.puzzle_completions done
    where done.user_id=auth.uid() and done.environment=p_environment and done.puzzle_id=c.puzzle_id)
    then c.replay_reward else c.first_reward end) into v_count,v_amount
    from wallet_private.puzzle_catalog c where c.puzzle_id=any(v_ids);
  if v_count<>cardinality(v_ids) then raise exception 'Timed puzzle catalog incomplete'; end if;
  select coalesce(sum(delta),0) into v_total from public.coin_wallet_entries where user_id=auth.uid() and environment=p_environment
   and kind='puzzle_reward' and created_at >= date_trunc('day',now() at time zone 'UTC') at time zone 'UTC';
  v_amount:=least(v_amount,greatest(0,1000-v_total));
  perform wallet_private.append_entry(auth.uid(),p_environment,v_amount,'puzzle_reward',v_key,v_payload,'Timed run reward','game');
  insert into wallet_private.puzzle_completions(user_id,environment,puzzle_id)
    select auth.uid(),p_environment,unnest(v_ids) on conflict do nothing;
 end if;
 select * into v_wallet from public.coin_wallets where user_id=auth.uid() and environment=p_environment;
 return v_wallet;
end; $$;
revoke all on function public.claim_timed_challenge_coins(text,text,text) from public,anon,authenticated,service_role;
grant execute on function public.claim_timed_challenge_coins(text,text,text) to authenticated;
commit;
