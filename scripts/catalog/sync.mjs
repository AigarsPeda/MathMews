/** Generate room registrations and insert-only server seeds from authored data. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const wallPatterns = new Set(['linen','stripe','sprig','panel','botanical','scallop','deco','beadboard','diamond','brick','trellis','tile','grasscloth','plaster','stars','daisy','tropical','waves','redbrick','concrete','arches','terrazzo','quatrefoil','gingham','wainscot','honeycomb','rainbow','mushroom','nautical']);
const floorPatterns = new Set(['classicOak','oak','checker','bamboo','tatami','concrete','slate','terrazzo','mosaic','parquet','stone','cork']);
const json = value => JSON.stringify(value, null, 2) + '\n';

export function planCatalog(root) {
  const read = file => fs.readFileSync(path.join(root, file), 'utf8');
  const rooms = JSON.parse(read('data/room-catalog.json'));
  const prices = JSON.parse(read('data/store-prices.json'));
  const ids = new Set();
  if (!Array.isArray(rooms) || !rooms.length) throw new Error('Room catalog must contain rooms');
  for (const room of rooms) {
    if (!/^room[1-9][0-9]*$/.test(room.id) || ids.has(room.id)) throw new Error(`Invalid or duplicate room ID: ${room.id}`);
    ids.add(room.id);
    if (!Number.isSafeInteger(room.initialPrice) || room.initialPrice < 0 || room.initialPrice > 2147483647) throw new Error(`Invalid initial price: ${room.id}`);
    for (const locale of ['en','lv']) for (const key of ['name','description']) {
      if (typeof room[locale]?.[key] !== 'string' || !room[locale][key].trim()) throw new Error(`Missing ${locale}.${key}: ${room.id}`);
    }
    for (const [surface, patterns] of [['wall',wallPatterns],['floor',floorPatterns]]) {
      if (!patterns.has(room[surface]?.pattern) || !['base','ink'].every(key => /^[0-9A-Fa-f]{6}$/.test(room[surface][key]))) throw new Error(`Invalid ${surface} finish: ${room.id}`);
    }
  }
  if (!ids.has('room1')) throw new Error('Keep the default room1 catalog entry');
  for (const id of Object.keys(prices.room)) if (!ids.has(id)) throw new Error(`Keep saved room ID ${id}; room removal needs a save migration`);
  prices.room = Object.fromEntries(rooms.map(room => [room.id,room.initialPrice]));
  const outputs = new Map([['data/store-prices.json',json(prices)]]);
  const sources = rooms.map(room => `  ${room.id}: require("@/assets/3d/rooms/${room.id}.png"),`).join('\n');
  outputs.set('constants/cat-rooms.ts',read('constants/cat-rooms.ts').replace(/export const CAT_ROOM_SOURCES = \{[\s\S]*?\} as const;/,
    `export const CAT_ROOM_SOURCES = {\n${sources}\n} as const;`));
  for (const locale of ['en','lv']) {
    const file = `locales/${locale}.json`, data = JSON.parse(read(file));
    data.store.roomStyles = Object.fromEntries(rooms.map(room => [room.id,room[locale]]));
    outputs.set(file,json(data));
  }
  const inventory = JSON.parse(read('scripts/3d/inventory.json'));
  inventory.entries = [...inventory.entries.filter(entry => entry.kind !== 'room'), ...rooms.map(room => ({id:room.id,kind:'room',animated:false}))];
  outputs.set('scripts/3d/inventory.json',json(inventory));

  // Applied migrations are history. Only seed IDs not registered by any prior
  // migration; never overwrite prices or promotions managed in Supabase.
  const known = new Set();
  for (const file of fs.readdirSync(path.join(root,'supabase/migrations')).filter(file => file.endsWith('.sql'))) {
    for (const match of read(`supabase/migrations/${file}`).matchAll(/\('(room|bed|toy|decoration|skin|life)'\s*,\s*'([^']+)'\s*,\s*\d+\)/g)) known.add(`${match[1]}:${match[2]}`);
  }
  const seed = [];
  for (const [kind, entries] of Object.entries(prices)) for (const [id, price] of Object.entries(entries)) {
    if (!/^[a-zA-Z0-9_-]+$/.test(id) || !Number.isSafeInteger(price) || price < 0 || price > 2147483647) throw new Error(`Invalid ${kind} initial price: ${id}`);
    if (!known.has(`${kind}:${id}`)) seed.push(`('${kind}','${id}',${price})`);
  }
  const sql = seed.length ? '-- Generated by npm run catalog:sync. Existing server prices and promotions are preserved.\nbegin;\ninsert into wallet_private.store_catalog(kind,item_id,price) values\n' + seed.join(',\n') + '\non conflict(kind,item_id) do nothing;\ncommit;\n' : null;
  return { outputs, sql, rooms };
}

export function syncCatalog(root, { check = false, now = new Date() } = {}) {
  const plan = planCatalog(root);
  const changed = [...plan.outputs].filter(([file,content]) => fs.readFileSync(path.join(root,file),'utf8') !== content);
  if (check) {
    if (changed.length || plan.sql) throw new Error(`Catalog is out of date. Run npm run catalog:sync. ${changed.map(([file]) => file).join(', ')}${plan.sql ? '; server seed missing' : ''}`);
    return { changed: [], migration: null, rooms: plan.rooms };
  }
  let migration = null;
  if (plan.sql) {
    const versions = fs.readdirSync(path.join(root,'supabase/migrations')).map(file => file.match(/^(\d+)_/)?.[1]).filter(Boolean);
    const timestamp = now.toISOString().replace(/\D/g,'').slice(0,14);
    const latest = versions.sort((a,b) => BigInt(a) < BigInt(b) ? -1 : 1).at(-1);
    const version = latest && BigInt(latest) >= BigInt(timestamp) ? String(BigInt(latest) + 1n) : timestamp;
    migration = `supabase/migrations/${version}_catalog_items.sql`;
    fs.writeFileSync(path.join(root,migration),plan.sql,{flag:'wx'});
  }
  for (const [file,content] of changed) fs.writeFileSync(path.join(root,file),content);
  return { changed: changed.map(([file]) => file), migration, rooms: plan.rooms };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const unknown = process.argv.slice(2).filter(arg => arg !== '--check');
  if (unknown.length) throw new Error(`Unknown options: ${unknown.join(' ')}`);
  const result = syncCatalog(process.cwd(),{check:process.argv.includes('--check')});
  console.log(`${result.rooms.length} rooms; ${result.changed.length} generated files updated.`);
  console.log(result.migration ? `New server seed: ${result.migration}. Apply through your database migration runner.` : 'Server registration is current. Existing server prices and promotions were preserved.');
}
