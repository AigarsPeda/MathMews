import fs from 'node:fs';
const quote = s => `'${s.replaceAll("'", "''")}'`;
const prices = JSON.parse(fs.readFileSync('data/store-prices.json','utf8'));
const store = Object.entries(prices).flatMap(([kind,items]) => Object.entries(items).map(([id,price]) => `(${quote(kind)},${quote(id)},${price})`));
store.push("('life','one',15)");
const rewards = {easy:[4,2],medium:[7,3],hard:[9,4]};
const puzzles = Object.keys(rewards).flatMap(tier => JSON.parse(fs.readFileSync(`assets/puzzles/${tier}.json`,'utf8')).map(p => {
 const [first,replay] = rewards[p.type === 'number_line' ? 'hard' : tier];
 return `(${quote(p.id)},${first},${replay})`;
}));
const sql = `-- Generated by node scripts/backend/generate-wallet-catalog.mjs\nbegin;\ninsert into wallet_private.store_catalog(kind,item_id,price) values\n${store.join(',\n')}\non conflict(kind,item_id) do update set price=excluded.price;\ninsert into wallet_private.puzzle_catalog(puzzle_id,first_reward,replay_reward) values\n${puzzles.join(',\n')}\non conflict(puzzle_id) do update set first_reward=excluded.first_reward,replay_reward=excluded.replay_reward;\ncommit;\n`;
fs.writeFileSync('supabase/migrations/202610160004_wallet_catalog.sql',sql);
