/** Derive gray previews and shareable GIFs from the shipped Blender artwork. */
import fs from 'node:fs/promises';
import { Buffer } from 'node:buffer';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';

export async function packAchievementMedia(selectedIds) {
  const catalog = JSON.parse(await fs.readFile('assets/3d/bosses/catalog.json', 'utf8'));
  const lessonIds = new Set(catalog.lessonScenes);
  const ids = selectedIds ?? catalog.scenes;
  const folder = 'assets/achievements';
  await fs.mkdir(folder, { recursive: true });
  const { frameWidth, frameHeight, frameCount, columns, fps } = catalog.outcome;
  for (const id of ids) {
    if (!catalog.scenes.includes(id)) throw new Error(`Unknown achievement scene: ${id}`);
    const ext = lessonIds.has(id) ? 'webp' : 'png';
    const scene = path.join('assets/3d/bosses', id);
    await sharp(path.join(scene, `state-0.${ext}`)).resize(384, 240).grayscale().toColourspace('srgb')
      .webp({ quality: 85, alphaQuality: 100 }).toFile(path.join(folder, `${id}-locked.webp`));
    const atlas = path.join(scene, `outcome.${ext}`);
    const width = 384, height = 240;
    const frames = [];
    for (let frame = 0; frame < frameCount; frame++) {
      frames.push(await sharp(atlas).extract({ left: frame % columns * frameWidth,
        top: Math.floor(frame / columns) * frameHeight, width: frameWidth, height: frameHeight })
        .resize(width, height).ensureAlpha().raw().toBuffer());
    }
    const delay = frames.map((_, index) => (Math.round((index + 1) * 100 / fps) - Math.round(index * 100 / fps)) * 10);
    await sharp(Buffer.concat(frames), { raw: { width, height: height * frameCount, channels: 4, pageHeight: height } })
      .gif({ loop: 0, delay, colours: 128, dither: .5, effort: 7 }).toFile(path.join(folder, `${id}.gif`));
  }
  await fs.writeFile('constants/achievement-media.ts', `// Generated by scripts/3d/pack-achievement-media.mjs from Blender scenes.\nexport const ACHIEVEMENT_MEDIA: Record<string, { locked: number; gif: number }> = {\n${catalog.scenes.map(id => `  "${id}": { locked: require("@/assets/achievements/${id}-locked.webp"), gif: require("@/assets/achievements/${id}.gif") }`).join(',\n')}\n};\n`);
  console.log(`Packed ${ids.length} gray achievement previews and transparent 16-frame GIFs.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const selected = process.argv.includes('--id') ? process.argv[process.argv.indexOf('--id') + 1].split(',') : undefined;
  await packAchievementMedia(selected);
}
