/** Package original, reward-only Blender comedy as offline movies and posters. */
import fs from 'node:fs/promises';
import { Buffer } from 'node:buffer';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';

export async function packAchievementMedia(selectedIds) {
  const catalog = JSON.parse(await fs.readFile('assets/3d/bosses/catalog.json', 'utf8'));
  const ids = selectedIds ?? catalog.scenes;
  const folder = 'assets/achievements', width = 512, height = 448, count = 24;
  await fs.mkdir(folder, { recursive: true });
  for (const id of ids) {
    if (!catalog.scenes.includes(id)) throw new Error(`Unknown achievement scene: ${id}`);
    const source = path.join('/tmp/brainpet-achievement-comedy', id);
    const raw = await Promise.all(Array.from({ length: count }, (_, n) => sharp(path.join(source, `frame-${String(n).padStart(2, '0')}.png`)).ensureAlpha().raw().toBuffer()));
    // Union bounds keep jumping actors and flying props in frame, with no camera jitter.
    let left = width - 1, top = height - 1, right = 0, bottom = 0;
    for (const pixels of raw) for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
      if (pixels[(y * width + x) * 4 + 3] < 12) continue;
      left = Math.min(left, x); right = Math.max(right, x); top = Math.min(top, y); bottom = Math.max(bottom, y);
    }
    const crop = { left, top, width: right - left + 1, height: bottom - top + 1 };
    const frames = [];
    for (const pixels of raw) frames.push(await sharp(pixels, { raw: { width, height, channels: 4 } }).extract(crop)
      .resize(width - 24, height - 24, { fit: 'contain', background: '#00000000' })
      .extend({ top: 12, bottom: 12, left: 12, right: 12, background: '#00000000' }).raw().toBuffer());
    await sharp(frames[0], { raw: { width, height, channels: 4 } }).grayscale().toColourspace('srgb').webp({ quality: 85, alphaQuality: 100 }).toFile(path.join(folder, `${id}-locked.webp`));
    await sharp(frames.at(-1), { raw: { width, height, channels: 4 } }).webp({ quality: 90, alphaQuality: 100 }).toFile(path.join(folder, `${id}-poster.webp`));
    // One second to read the setup and a held punchline make the loop intelligible.
    const delay = frames.map((_, n) => n === 0 ? 900 : n === count - 1 ? 1350 : n % 2 ? 120 : 130);
    await sharp(Buffer.concat(frames), { raw: { width, height: height * count, channels: 4, pageHeight: height } })
      .gif({ loop: 0, delay, colours: 96, dither: 0, effort: 7 }).toFile(path.join(folder, `${id}.gif`));
    console.log(`Packed ${id}`);
  }
  const registry = `// Generated by scripts/3d/pack-achievement-media.mjs from Blender scenes.\nexport const ACHIEVEMENT_MEDIA: Record<string, { locked: number; poster: number; gif: number }> = {\n${catalog.scenes.map(id => `  "${id}": { locked: require("@/assets/achievements/${id}-locked.webp"), poster: require("@/assets/achievements/${id}-poster.webp"), gif: require("@/assets/achievements/${id}.gif") }`).join(',\n')}\n};\n`;
  if (await fs.readFile('constants/achievement-media.ts', 'utf8') !== registry) await fs.writeFile('constants/achievement-media.ts', registry);
  console.log(`Packed ${ids.length} original reward movies, posters and locked previews.`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const selected = process.argv.includes('--id') ? process.argv[process.argv.indexOf('--id') + 1].split(',') : undefined;
  await packAchievementMedia(selected);
}
