/** Package original, reward-only Blender comedy as offline movies and posters. */
import fs from 'node:fs/promises';
import { Buffer } from 'node:buffer';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { composeFilmFrame, filmDelays, filmShots } from './achievement-film-edit.mjs';
const execFileAsync = promisify(execFile);
const gifsicle = process.env.GIFSICLE_BIN ?? 'gifsicle';

export async function packAchievementMedia(selectedIds) {
  // Like Blender, Gifsicle is an authoring tool, never an app dependency.
  await execFileAsync(gifsicle, ['--version']).catch(() => { throw new Error('Install Gifsicle or set GIFSICLE_BIN to its executable before packaging rewards.'); });
  const catalog = JSON.parse(await fs.readFile('assets/3d/bosses/catalog.json', 'utf8'));
  const ids = selectedIds ?? catalog.scenes;
  const folder = 'assets/achievements', width = 512, height = 448, count = 48;
  await fs.mkdir(folder, { recursive: true });
  for (const id of ids) {
    if (!catalog.scenes.includes(id)) throw new Error(`Unknown achievement scene: ${id}`);
    const [world, kind = 'trophy'] = id.split('-');
    const source = path.join('/tmp/brainpet-reward-studio', kind);
    // Render at 1.5x delivery resolution, then move the camera across both layers.
    // The shared edit preserves contact and perspective during the close-up.
    const stage = await fs.readFile(`/tmp/brainpet-reward-studio/${world}-stage.png`);
    const frames = [];
    const shots = await filmShots('/tmp/brainpet-reward-studio', kind);
    for (let n = 0; n < count; n++) frames.push(await composeFilmFrame(stage, path.join(source, `frame-${String(n).padStart(2, '0')}.png`), shots[n]));
    await sharp(frames[0], { raw: { width, height, channels: 4 } }).grayscale().toColourspace('srgb').webp({ quality: 85, alphaQuality: 100 }).toFile(path.join(folder, `${id}-locked.webp`));
    await sharp(frames.at(-1), { raw: { width, height, channels: 4 } }).webp({ quality: 90, alphaQuality: 100 }).toFile(path.join(folder, `${id}-poster.webp`));
    // Hesitations, impacts and double takes get scene-specific holds.
    const delay = filmDelays(kind);
    await sharp(Buffer.concat(frames), { raw: { width, height: height * count, channels: 4, pageHeight: height } })
      .gif({ loop: 0, delay, colours: 256, dither: 0, effort: 7 }).toFile(path.join(folder, `${id}.gif`));
    await execFileAsync(gifsicle, ['--optimize=3', '--no-dither', '--lossy=45', '--colors=192', '--batch', path.join(folder, `${id}.gif`)]);
    console.log(`Packed ${id}`);
  }
  const registry = `// Generated by scripts/3d/pack-achievement-media.mjs from Blender scenes.\nexport const ACHIEVEMENT_MEDIA: Record<string, { locked: number; poster: number; gif: number }> = {\n${catalog.scenes.map(id => `  "${id}": { locked: require("@/assets/achievements/${id}-locked.webp"), poster: require("@/assets/achievements/${id}-poster.webp"), gif: require("@/assets/achievements/${id}.gif") }`).join(',\n')}\n};\n`;
  if (await fs.readFile('constants/achievement-media.ts', 'utf8') !== registry) await fs.writeFile('constants/achievement-media.ts', registry);
  console.log(`Packed ${ids.length} original reward movies, posters and locked previews.`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const selected = process.argv.includes('--id') ? process.argv[process.argv.indexOf('--id') + 1].split(',') : undefined;
  await packAchievementMedia(selected);
}
