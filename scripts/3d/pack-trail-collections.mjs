import fs from 'node:fs/promises';
import sharp from 'sharp';

const sources = [];
const manifest = [];
for (const [collection, prefix] of [['easy', 'e'], ['medium', 'm'], ['hard', 'h']]) {
  const destination = `assets/3d/trail-collections/${collection}`;
  await fs.mkdir(destination, { recursive: true });
  for (let i = 1; i <= 20; i++) {
    const id = `${prefix}${String(i).padStart(2, '0')}`;
    const source = `prototypes/trail-collections/${collection}`;
    await sharp(`${source}/renders/${id}.png`).resize(384, 384).webp({ quality: 93, alphaQuality: 100, effort: 4 }).toFile(`${destination}/${id}.webp`);
    sources.push(`  ${id}: require("@/assets/3d/trail-collections/${collection}/${id}.webp"),`);
    const metadata = JSON.parse(await fs.readFile(`${source}/${id}.json`, 'utf8'));
    manifest.push({ ...metadata, bytes: (await fs.stat(`${destination}/${id}.webp`)).size });
  }
}
await fs.writeFile('constants/trail-collection-images.ts', `// Generated by scripts/3d/pack-trail-collections.mjs. Keep Metro asset references static.\nexport const TrailCollectionImages = {\n${sources.join('\n')}\n} as const;\n`);
await fs.writeFile('prototypes/trail-collections/manifest.json', `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Packed ${manifest.length} Blender assets: ${Math.round(manifest.reduce((n, item) => n + item.bytes, 0) / 1024)} KB`);
