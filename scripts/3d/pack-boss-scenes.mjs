/** Pack original Blender renders into small native atlases. Re-run after rendering. */
import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { bossStories } from '../puzzles/boss-stories.mjs';

const root = path.resolve(import.meta.dirname, '../..');
const ids = Object.keys(bossStories);
const selected = process.argv.includes('--id') ? [process.argv[process.argv.indexOf('--id') + 1]] : ids;
for (const id of selected) {
  if (!ids.includes(id)) throw new Error(`Unknown boss scene: ${id}`);
  const folder = path.join(root, 'assets/3d/bosses', id);
  for (const [prefix, count] of [['reaction-1',8],['reaction-2',8],['outcome',16]]) {
    const frames = Array.from({ length: count }, (_, i) => ({
      input: path.join(folder, `${prefix}-${String(i).padStart(2, '0')}.png`),
      left: (i % 4) * 512, top: Math.floor(i / 4) * 320,
    }));
    await sharp({ create: { width: 2048, height: count / 4 * 320, channels: 4, background: '#00000000' } })
      .composite(frames).png({ palette: false, compressionLevel: 9 }).toFile(path.join(folder, `${prefix}.png`));
    for (const frame of frames) await fs.rm(frame.input);
  }
}
const entries = ids.map(id => `  ${id}: { states: [${[0,1,2,3].map(n => `require("@/assets/3d/bosses/${id}/state-${n}.png")`).join(', ')}], reactions: [require("@/assets/3d/bosses/${id}/reaction-1.png"), require("@/assets/3d/bosses/${id}/reaction-2.png")], outcome: require("@/assets/3d/bosses/${id}/outcome.png") }`);
await fs.writeFile(path.join(root, 'constants/boss-scene-assets.ts'),
  `// Generated by scripts/3d/pack-boss-scenes.mjs. Static requires let Metro bundle native assets.\nexport type BossSceneAssets = { states: [number, number, number, number]; reactions: [number, number]; outcome: number };\nexport const BOSS_SCENE_ASSETS: Record<string, BossSceneAssets> = {\n${entries.join(',\n')}\n};\n`);
await fs.writeFile(path.join(root, 'assets/3d/bosses/catalog.json'), JSON.stringify({
  generator: 'scripts/3d/build-boss-scenes.py', sourceDirectory: 'prototypes/boss-scenes',
  still: { width: 768, height: 480, count: 4 },
  actor: { model: 'assets/3d/native/cat-orange.glb', staging: 'cat-staging.json' },
  reaction: { width: 2048, height: 640, columns: 4, rows: 2, frameCount: 8, fps: 8, count: 2 },
  outcome: { width: 2048, height: 1280, columns: 4, rows: 4, frameWidth: 512, frameHeight: 320, frameCount: 16, fps: 8 },
  scenes: ids,
}, null, 2) + '\n');
console.log(`Packed ${selected.length} boss scenes with two task reactions and a final outcome.`);
